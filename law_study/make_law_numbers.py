"""Generate output/tex/macros/v14_numbers.tex and the law tables from results/law_summary.json (law_study.py numbers)."""
import json, math
from pathlib import Path
HERE = Path(__file__).resolve().parent
MAN = HERE.parent / 'output' / 'tex'
(MAN / 'macros').mkdir(parents=True, exist_ok=True); (MAN / 'tables/data').mkdir(parents=True, exist_ok=True)
S = json.loads((HERE / 'results/law_summary.json').read_text())
cell = {(r['H'], r['sigma'], r['F']): r for r in S}
FIG = cell[(0.1, 0.5, 0.5)]


def v(r, k, w='rclh'): return r[k][w][0]
def hw(r, k, w='ref'): return r[k][w][1]
def pct(x, d=1): return f'{100 * x:.{d}f}\\%'
def f3(x): return f'{x:.3f}'
def sci(x):
    e = int(math.floor(math.log10(abs(x)))); m = x / 10 ** e
    return f'{m:.1f}\\times10^{{{e}}}'


QKEYS = [k for k in S[0] if k.startswith(('Yq', 'Xq'))]
PKEYS = ['P_low_T', 'P_low_path', 'P_short']
qrel = max(abs(r[k]['diff'][0]) / abs(r[k]['ref'][0]) for r in S for k in QKEYS)
qrel_key = max(((abs(r[k]['diff'][0]) / abs(r[k]['ref'][0]), k, r['H'], r['sigma'], r['F']) for r in S for k in QKEYS))
pabs = max(abs(r[k]['diff'][0]) for r in S for k in PKEYS)
pabs_key = max(((abs(r[k]['diff'][0]), k, r['H'], r['sigma'], r['F']) for r in S for k in PKEYS))
agree = sum(r[k]['agree'] for r in S for k in QKEYS + PKEYS); total = len(S) * len(QKEYS + PKEYS)
corr_min = min(r['corr_Y'][0] for r in S)
pathT = max(r['pathL2_T'][0] for r in S); pathY = max(r['pathL2_Y'][0] for r in S)
# Gaussian (moment-matched with the exact mean and variance)
g_q1 = [(abs(r['Xq0.01']['gauss'][0] - r['Xq0.01']['ref'][0]) / r['Xq0.01']['ref'][0]) for r in S]
g_neg = sum(r['Xq0.01']['gauss'][0] < 0 for r in S)
g_ratio = [r['P_low_T']['gauss'][0] / r['P_low_T']['ref'][0] for r in S if r['P_low_T']['ref'][0] >= 0.01]
g_rare = [r for r in S if r['P_low_T']['ref'][0] < 0.01]
g_rare_min = min(r['P_low_T']['gauss'][0] / max(r['P_low_T']['ref'][0], 1e-12) for r in g_rare if r['P_low_T']['ref'][0] > 0)
g_yq1 = [abs(r['Yq0.01']['gauss'][0] - r['Yq0.01']['ref'][0]) / r['Yq0.01']['ref'][0] for r in S]
ref_q_hw = max(r[k]['ref'][1] / abs(r[k]['ref'][0]) for r in S for k in QKEYS)
ref_p_hw = max(r[k]['ref'][1] for r in S for k in PKEYS)
share = {H: [r['ledger'] / r['Yvar']['ref'][0] for r in S if r['H'] == H] for H in (0.1, 0.5, 0.8)}
led_rel = max(abs(r['ledger_mc'][0] - r['ledger']) / r['ledger'] for r in S)
neg = max(r['neg'][0] for r in S)

m = {
 'lawCells': str(len(S)), 'lawSamples': '262{,}144', 'lawAgree': str(agree), 'lawTotal': str(total),
 'lawCorrMin': f'{corr_min:.4f}', 'lawPathTmax': pct(pathT), 'lawPathYmax': pct(pathY),
 'lawQrelMax': pct(qrel, 2), 'lawPabsMax': f'{pabs:.4f}',
 'lawRefQhw': pct(ref_q_hw, 2), 'lawRefPhw': f'{ref_p_hw:.4f}',
 'lawGaussQoneMin': pct(min(g_q1), 0), 'lawGaussQoneMax': pct(max(g_q1), 0), 'lawGaussNeg': str(g_neg),
 'lawGaussRatioMin': f'{min(g_ratio):.2f}', 'lawGaussRatioMax': f'{max(g_ratio):.1f}',
 'lawGaussYqMax': pct(max(g_yq1), 0),
 'lawGaussResolved': str(len(g_ratio)), 'lawGaussRare': str(len(g_rare)),
 'lawGaussRareMin': f'{g_rare_min:.0f}',
 'lawShareLowMin': pct(min(share[0.1])), 'lawShareLowMax': pct(max(share[0.1])),
 'lawShareHighMax': pct(max(share[0.8]), 2), 'lawShareMidMax': pct(max(share[0.5]), 2),
 'lawLedgerRel': pct(led_rel, 2),
 # figure cell H = 0.1, sigma = F = 0.5
 'lawFigXqRef': f3(v(FIG, 'Xq0.01', 'ref')), 'lawFigXqRclh': f3(v(FIG, 'Xq0.01')), 'lawFigXqGauss': f3(FIG['Xq0.01']['gauss'][0]),
 'lawFigPlowRef': pct(v(FIG, 'P_low_T', 'ref'), 2), 'lawFigPlowRclh': pct(v(FIG, 'P_low_T'), 2), 'lawFigPlowGauss': pct(FIG['P_low_T']['gauss'][0], 2),
 'lawFigPpathRef': pct(v(FIG, 'P_low_path', 'ref'), 1), 'lawFigPpathRclh': pct(v(FIG, 'P_low_path'), 1),
 'lawFigSolveS': f"{FIG['solve_seconds']:.2f}",
}
LS = [r for r in json.loads((HERE / 'results/ledger_split.json').read_text()) if r['H'] == 0.1]
m['lawDiagLowMin'] = pct(min(r['diag_share'] for r in LS)); m['lawDiagLowMax'] = pct(max(r['diag_share'] for r in LS))
m['lawOffLowMin'] = pct(min(-r['off_share'] for r in LS)); m['lawOffLowMax'] = pct(max(-r['off_share'] for r in LS))
lines = ['% Generated by law_study/make_law_numbers.py -- do not edit by hand.']
lines += [f'\\newcommand{{\\{k}}}{{{x}}}' for k, x in m.items()]
(MAN / 'macros/v14_numbers.tex').write_text('\n'.join(lines) + '\n', encoding='utf-8')

# main-text table body: sigma = F = 0.5
rows = []
for H in (0.1, 0.5, 0.8):
    r = cell[(H, 0.5, 0.5)]
    rows.append(f"{H:.2f} & {f3(v(r,'Yq0.01','ref'))} & {f3(v(r,'Yq0.01'))} & {f3(r['Yq0.01']['gauss'][0])}"
                f" & {f3(v(r,'Xq0.01','ref'))} & {f3(v(r,'Xq0.01'))} & {f3(r['Xq0.01']['gauss'][0])}"
                f" & {100*v(r,'P_low_T','ref'):.2f} & {100*v(r,'P_low_T'):.2f} & {100*r['P_low_T']['gauss'][0]:.2f}"
                f" & {100*v(r,'P_low_path','ref'):.2f} & {100*v(r,'P_low_path'):.2f}\\\\")
body = [r'\begin{tabular}{@{}c ccc ccc ccc cc@{}}', r'\toprule',
        r' & \multicolumn{3}{c}{1\% quantile of $\Yc_T$} & \multicolumn{3}{c}{1\% quantile of $X_T$} & \multicolumn{3}{c}{$\Pr(X_T<x^\ast/2)$ (\%)} & \multicolumn{2}{c}{$\Pr(\min_iX_{t_i}<x^\ast/2)$ (\%)}\\',
        r'\cmidrule(lr){2-4}\cmidrule(lr){5-7}\cmidrule(lr){8-10}\cmidrule(l){11-12}',
        r'$H$ & exact & \RCLH & Gauss. & exact & \RCLH & Gauss. & exact & \RCLH & Gauss. & exact & \RCLH\\', r'\midrule'] + rows + [r'\bottomrule', r'\end{tabular}']
(MAN / 'tables/data/tab_fishery_law.tex').write_text('% Generated by law_study/make_law_numbers.py -- do not edit by hand.\n' + '\n'.join(body) + '\n', encoding='utf-8')

# supplement table: all 18 cells
srows = []
for r in S:
    qd = max(abs(r[k]['diff'][0]) / abs(r[k]['ref'][0]) for k in QKEYS)
    pd = max(abs(r[k]['diff'][0]) for k in PKEYS)
    gq = abs(r['Xq0.01']['gauss'][0] - r['Xq0.01']['ref'][0]) / r['Xq0.01']['ref'][0]
    srows.append(f"{r['H']:.1f} & {r['sigma']:.2f} & {r['F']:.1f} & {r['corr_Y'][0]:.4f} & {100*r['pathL2_T'][0]:.2f} & {100*qd:.2f} & {pd:.4f}"
                 f" & {100*v(r,'P_low_T','ref'):.2f} & {100*r['P_low_T']['gauss'][0]:.2f} & {100*gq:.0f} & {100*r['ledger']/r['Yvar']['ref'][0]:.2f}\\\\")
sbody = [r'\begin{tabular}{@{}ccc cc cc cc cc@{}}', r'\toprule',
         r'$H$ & $\sigma$ & $F$ & corr.\ $\Yc_T$ & path err.\ $X_T$ (\%) & max quantile diff.\ (\%) & max prob.\ diff. & $\Pr(X_T<x^\ast/2)$ (\%) & Gauss.\ (\%) & Gauss.\ 1\% quantile err.\ (\%) & residual share (\%)\\',
         r'\midrule'] + srows + [r'\bottomrule', r'\end{tabular}']
(MAN / 'tables/data/tab_supp_fishery_law.tex').write_text('% Generated by law_study/make_law_numbers.py -- do not edit by hand.\n' + '\n'.join(sbody) + '\n', encoding='utf-8')
print(json.dumps(m, indent=1)); print('worst quantile', qrel_key); print('worst prob', pabs_key)
